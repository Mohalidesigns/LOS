import { useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { CheckCircle2, CircleDashed, Download, FileSignature, Mail, Printer, Send } from 'lucide-react';
import { idempotencyKey } from '@/api/client';
import { documentsApi } from '@/api/lending';
import { offersApi, type Offer, type OfferSignatory } from '@/api/offers';
import { isApiProblem } from '@/api/problem';
import { Banner, Button, CardHeader, DateTimeText, ErrorSummary, KebabMenu, MoneyText, Pill, SectionError, Skeleton, useToast } from '@/components';
import { useCase } from '@/features/applications/case/CaseContext';
import { Collapsible } from '@/features/applications/credit/CreditParts';
import { problemLines } from '@/features/applications/credit/domain';
import { refreshCase } from '@/features/applications/queries';
import { saveBlob, shortHash } from '@/lib/download';
import { cn } from '@/lib/cn';
import { acceptReason, currentOffer, daysLeft, issueReason, OFFER_STATUS_META, reissueReason, ROLE_LABEL, workReason } from './domain';
import { AcceptDialog, DeclineDialog, ReissueDialog, SignDialog } from './OfferDialogs';
import { applicationOffersQuery } from './queries';

type Dialog = { kind: 'sign'; signatory: OfferSignatory } | { kind: 'accept' } | { kind: 'decline' } | { kind: 'reissue' } | null;

/** SCR-OFR-01/02: issue, key facts, schedule, delivery, ordered signing, acceptance. */
export function OfferTab() {
  const { app, permissions } = useCase();
  const list = useQuery(applicationOffersQuery(app.id));
  const qc = useQueryClient();
  const toast = useToast();
  const [key] = useState(idempotencyKey);
  const issue = useMutation({
    mutationFn: () => offersApi.issue(app.id, key),
    onSuccess: async (o) => {
      toast.show(`Offer #${o.sequence} issued. Deliver it to the customer next.`, 'success');
      await refreshCase(qc, app.id);
    },
  });

  if (list.isPending) return <Skeleton className="h-[20rem] w-full rounded-card" />;
  if (list.isError) return <SectionError error={list.error} title="Offers couldn't load" onRetry={() => void list.refetch()} />;

  const current = currentOffer(list.data);
  const reason = issueReason(app.status, permissions, current?.status === 'issued');
  const canIssueNow = app.status === 'approved' || app.status === 'counter_offered';
  const earlier = list.data.filter((o) => o.id !== current?.id);

  return (
    <div className="space-y-5">
      {issue.error && <ErrorSummary title="The offer was not issued" problem={isApiProblem(issue.error) ? issue.error : null} messages={problemLines(issue.error)} />}
      {(!current || (canIssueNow && current.status !== 'issued')) && (
        <section aria-labelledby="ofr-issue" className="rounded-card border bg-surface p-5 shadow-card">
          <CardHeader
            title="Offer"
            titleId="ofr-issue"
            level={2}
            actions={
              <Button leadingIcon={<FileSignature aria-hidden="true" className="h-icon-sm w-icon-sm" />} disabledReason={reason} loading={issue.isPending} onClick={() => issue.mutate()}>
                Issue offer
              </Button>
            }
          />
          <p className="text-body-sm text-secondary">
            {canIssueNow
              ? `The offer uses the ${app.status === 'counter_offered' ? 'counter-offer' : 'approved'} terms, a repayment schedule generated by the core banking system, and the product’s offer template. It is produced as a PDF and filed under Documents.`
              : 'An offer can be issued once the application is approved or counter-offered.'}
          </p>
        </section>
      )}
      {current && <OfferDetail offer={current} permissions={permissions} />}
      {earlier.length > 0 && (
        <section aria-labelledby="ofr-hist" className="rounded-card border bg-surface p-5 shadow-card">
          <CardHeader title="Earlier offers" titleId="ofr-hist" level={2} />
          <ul className="space-y-2">
            {earlier.map((o) => (
              <li key={o.id} className="flex flex-wrap items-center justify-between gap-2 rounded-control border p-3 text-body-sm">
                <span>
                  Offer #{o.sequence} · issued <DateTimeText value={o.issued_at} /> · <MoneyText amount={o.terms.amount.amount} currency={o.terms.amount.currency} />
                  {o.decision?.reason_code && <> · {o.decision.reason_code}</>}
                </span>
                <Pill tone={OFFER_STATUS_META[o.status].tone}>{OFFER_STATUS_META[o.status].label}</Pill>
              </li>
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}

function OfferDetail({ offer, permissions }: { offer: Offer; permissions: ReadonlySet<string> }) {
  const [dialog, setDialog] = useState<Dialog>(null);
  const qc = useQueryClient();
  const toast = useToast();
  const [deliverKey] = useState(idempotencyKey);
  const deliver = useMutation({
    mutationFn: (channel: 'email' | 'print') => offersApi.deliver(offer.id, { channel }, `${deliverKey}-${channel}-${offer.deliveries.length}`),
    onSuccess: async (_o, channel) => {
      toast.show(channel === 'email' ? 'Email queued to the borrower.' : 'Printed copy recorded.', 'success');
      await refreshCase(qc, offer.application_id);
    },
  });
  const download = useMutation({
    mutationFn: async ({ documentId, versionId, name }: { documentId: string; versionId: string; name: string }) => saveBlob(await documentsApi.content(documentId, versionId), name),
  });
  const work = workReason(offer, permissions);
  const kf = offer.key_facts;
  const cur = offer.terms.amount.currency;
  const left = daysLeft(offer.valid_until);
  const money = (a: string) => <MoneyText amount={a} currency={cur} />;

  return (
    <>
      {offer.status === 'issued' && offer.is_expired && (
        <Banner tone="warning" title="This offer has expired">
          It can no longer be signed or accepted. It moves to Expired at the next hourly check.
        </Banner>
      )}
      <div className="grid gap-5 xl:grid-cols-[minmax(0,1fr)_22rem]">
        <div className="min-w-0 space-y-5">
          <section aria-labelledby="ofr-main" className="rounded-card border bg-surface p-5 shadow-card">
            <CardHeader
              title={`Offer #${offer.sequence}`}
              titleId="ofr-main"
              level={2}
              subtitle={`Template ${offer.template.key} v${offer.template.version_no} · ${offer.terms.source === 'counter_offer' ? 'counter-offer terms' : 'approved terms'} · issued by ${offer.issued_by?.name ?? 'staff'}`}
              actions={
                <div className="flex flex-wrap items-center gap-2">
                  <Pill tone={OFFER_STATUS_META[offer.status].tone}>{OFFER_STATUS_META[offer.status].label}</Pill>
                  {offer.status === 'issued' && (
                    <KebabMenu
                      label="Offer actions"
                      items={[
                        { label: 'Re-issue offer', disabledReason: reissueReason(offer, permissions), onSelect: () => setDialog({ kind: 'reissue' }) },
                        { label: 'Customer rejects or negotiates', disabledReason: work, danger: true, onSelect: () => setDialog({ kind: 'decline' }) },
                      ]}
                    />
                  )}
                </div>
              }
            />
            <dl className="grid grid-cols-2 gap-4 sm:grid-cols-4">
              <div>
                <dt className="text-meta text-tertiary">Amount</dt>
                <dd className="text-title text-emphasis">{money(offer.terms.amount.amount)}</dd>
              </div>
              <div>
                <dt className="text-meta text-tertiary">Tenor</dt>
                <dd className="text-title text-emphasis">{offer.terms.tenor_months} months</dd>
              </div>
              <div>
                <dt className="text-meta text-tertiary">Rate</dt>
                <dd className="text-title text-emphasis">{Number(offer.terms.rate_percent).toFixed(2)}% p.a.</dd>
              </div>
              <div>
                <dt className="text-meta text-tertiary">Instalment</dt>
                <dd className="text-title text-emphasis">{money(offer.terms.instalment.amount)}</dd>
              </div>
            </dl>
            <p className="mt-3 text-body-sm text-secondary">
              Valid until <DateTimeText value={offer.valid_until} style="date" />
              {offer.status === 'issued' && !offer.is_expired && ` (${left} day${left === 1 ? '' : 's'} left)`}. PDF <span className="ref">{shortHash(offer.document.sha256)}</span>
            </p>
            <div className="mt-3">
              <Button
                size="sm"
                variant="secondary"
                leadingIcon={<Download aria-hidden="true" className="h-icon-sm w-icon-sm" />}
                loading={download.isPending}
                onClick={() => download.mutate({ documentId: offer.document.document_id, versionId: offer.document.version_id, name: `offer-${offer.sequence}.pdf` })}
              >
                Download offer letter
              </Button>
            </div>
          </section>

          <section aria-labelledby="ofr-kf" className="rounded-card border bg-surface p-5 shadow-card">
            <CardHeader title="Key facts and cost of credit" titleId="ofr-kf" level={2} subtitle={`Disclosure method ${kf.method} (pending verification against the CBN rules, G-24)`} />
            <dl className="grid gap-x-6 gap-y-2 text-body-sm sm:grid-cols-2">
              {(
                [
                  ['Total interest', money(kf.total_interest)],
                  ['Total fees', money(kf.total_fees)],
                  ['Total cost of credit', money(kf.total_cost_of_credit)],
                  ['Total amount repayable', money(kf.total_repayable)],
                  ['Amount received (after upfront fees)', money(kf.net_disbursed)],
                  ['APR', `${kf.apr_percent}%`],
                  ['Effective annual rate', `${kf.effective_annual_rate_percent}%`],
                  ['Cooling-off', kf.cooling_off_days > 0 ? `${kf.cooling_off_days} days` : 'None'],
                ] as const
              ).map(([label, value]) => (
                <div key={label} className="flex justify-between gap-3 border-b py-1.5">
                  <dt className="text-secondary">{label}</dt>
                  <dd className="tabular font-semibold text-primary">{value}</dd>
                </div>
              ))}
            </dl>
            {kf.fees.length > 0 && (
              <ul className="mt-3 space-y-1 text-meta text-tertiary">
                {kf.fees.map((f) => (
                  <li key={f.code}>
                    {f.name} ({f.type}): {f.costed ? <MoneyText amount={f.amount} currency={cur} /> : 'charged only if it arises'}
                  </li>
                ))}
              </ul>
            )}
            <Collapsible className="mt-4" summary={`Repayment schedule · ${offer.schedule.length} instalments (from the core banking system)`}>
              <div className="overflow-x-auto">
                <table className="w-full text-body-sm">
                  <caption className="sr-only">Repayment schedule</caption>
                  <thead>
                    <tr className="text-left text-meta text-tertiary">
                      <th scope="col" className="py-1.5 pr-3">No.</th>
                      <th scope="col" className="py-1.5 pr-3">Due</th>
                      <th scope="col" className="py-1.5 pr-3 text-right">Principal</th>
                      <th scope="col" className="py-1.5 pr-3 text-right">Interest</th>
                      <th scope="col" className="py-1.5 pr-3 text-right">Instalment</th>
                      <th scope="col" className="py-1.5 text-right">Balance</th>
                    </tr>
                  </thead>
                  <tbody>
                    {offer.schedule.map((r) => (
                      <tr key={r.number} className="border-t">
                        <td className="py-1.5 pr-3 tabular">{r.number}</td>
                        <td className="py-1.5 pr-3 tabular">{r.due_date}</td>
                        <td className="py-1.5 pr-3 text-right">{money(r.principal)}</td>
                        <td className="py-1.5 pr-3 text-right">{money(r.interest)}</td>
                        <td className="py-1.5 pr-3 text-right">{money(r.total)}</td>
                        <td className="py-1.5 text-right">{money(r.closing_balance)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Collapsible>
          </section>
        </div>

        <aside aria-label="Delivery, signing and acceptance" className="min-w-0 space-y-5">
          <section aria-labelledby="ofr-sign" className="rounded-card border bg-surface p-5 shadow-card">
            <CardHeader title="Signing" titleId="ofr-sign" level={2} subtitle="Wet signatures, in this order" />
            <ol className="space-y-2">
              {offer.signatories.map((s) => (
                <li key={s.id} className={cn('rounded-control border p-3', s.is_next && offer.status === 'issued' && 'border-accent bg-subtle')}>
                  <div className="flex items-start justify-between gap-2">
                    <div className="flex min-w-0 gap-2">
                      {s.signed ? <CheckCircle2 aria-hidden="true" className="mt-0.5 h-icon w-icon shrink-0 text-success" /> : <CircleDashed aria-hidden="true" className="mt-0.5 h-icon w-icon shrink-0 text-tertiary" />}
                      <div className="min-w-0">
                        <p className="text-body-sm font-semibold text-primary">
                          {s.position}. {s.name}
                        </p>
                        <p className="text-meta text-tertiary">
                          {ROLE_LABEL[s.role]}
                          {s.signed && s.signed_at && (
                            <>
                              {' '}
                              · signed <DateTimeText value={s.signed_at} />
                              {s.witness_name && ` · witness ${s.witness_name}`}
                            </>
                          )}
                        </p>
                      </div>
                    </div>
                    {s.is_next && offer.status === 'issued' && (
                      <Button size="sm" disabledReason={work} onClick={() => setDialog({ kind: 'sign', signatory: s })}>
                        Record
                      </Button>
                    )}
                  </div>
                </li>
              ))}
            </ol>
            {offer.status === 'issued' && (
              <Button className="mt-4 w-full" disabledReason={acceptReason(offer, permissions)} onClick={() => setDialog({ kind: 'accept' })}>
                Accept with executed agreement
              </Button>
            )}
            {offer.agreement && (
              <div className="mt-4 rounded-control bg-subtle p-3 text-body-sm">
                <p className="font-semibold text-primary">Executed agreement on file</p>
                <p className="text-meta text-tertiary">
                  <DateTimeText value={offer.agreement.executed_at} /> · sha256 <span className="ref">{shortHash(offer.agreement.sha256)}</span>
                </p>
                <Button
                  size="sm"
                  variant="secondary"
                  className="mt-2"
                  leadingIcon={<Download aria-hidden="true" className="h-icon-sm w-icon-sm" />}
                  onClick={() => offer.agreement && download.mutate({ documentId: offer.agreement.document_id, versionId: offer.agreement.version_id, name: `agreement-${offer.sequence}.pdf` })}
                >
                  Download agreement
                </Button>
              </div>
            )}
          </section>

          <section aria-labelledby="ofr-del" className="rounded-card border bg-surface p-5 shadow-card">
            <CardHeader title="Delivery" titleId="ofr-del" level={2} />
            {deliver.error && <ErrorSummary title="Not delivered" problem={isApiProblem(deliver.error) ? deliver.error : null} messages={problemLines(deliver.error)} />}
            {offer.status === 'issued' && (
              <div className="mb-3 flex flex-wrap gap-2">
                <Button size="sm" variant="secondary" leadingIcon={<Mail aria-hidden="true" className="h-icon-sm w-icon-sm" />} disabledReason={work} loading={deliver.isPending && deliver.variables === 'email'} onClick={() => deliver.mutate('email')}>
                  Email borrower
                </Button>
                <Button size="sm" variant="secondary" leadingIcon={<Printer aria-hidden="true" className="h-icon-sm w-icon-sm" />} disabledReason={work} loading={deliver.isPending && deliver.variables === 'print'} onClick={() => deliver.mutate('print')}>
                  Record printed copy
                </Button>
              </div>
            )}
            {offer.deliveries.length === 0 ? (
              <p className="text-body-sm text-secondary">Not delivered yet.</p>
            ) : (
              <ul className="space-y-1.5 text-body-sm">
                {offer.deliveries.map((d) => (
                  <li key={d.id} className="flex flex-wrap items-center justify-between gap-2">
                    <span className="inline-flex items-center gap-1.5 text-primary">
                      {d.channel === 'email' ? <Send aria-hidden="true" className="h-icon-sm w-icon-sm" /> : <Printer aria-hidden="true" className="h-icon-sm w-icon-sm" />}
                      {d.channel === 'email' ? `Email ${d.recipient ?? ''}` : 'Printed copy'} · <DateTimeText value={d.requested_at} />
                    </span>
                    <Pill tone={d.status === 'failed' ? 'danger' : d.status === 'queued' ? 'warning' : 'success'}>{d.status === 'recorded' ? 'Recorded' : d.status.replace(/^\w/, (c) => c.toUpperCase())}</Pill>
                  </li>
                ))}
              </ul>
            )}
          </section>
        </aside>
      </div>
      {dialog?.kind === 'sign' && <SignDialog offer={offer} signatory={dialog.signatory} onClose={() => setDialog(null)} />}
      {dialog?.kind === 'accept' && <AcceptDialog offer={offer} onClose={() => setDialog(null)} />}
      {dialog?.kind === 'decline' && <DeclineDialog offer={offer} onClose={() => setDialog(null)} />}
      {dialog?.kind === 'reissue' && <ReissueDialog offer={offer} onClose={() => setDialog(null)} />}
    </>
  );
}
